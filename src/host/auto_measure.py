"""One-command measurement: hardware check -> (calibration) -> scan -> model.

    python auto_measure.py check
    python auto_measure.py calibrate --out D:/run
    python auto_measure.py run --out D:/run --z0 73 --z1 77 --layers 3 \
        --azimuths 0,90,180,270 --frames 3 --tx 1 --datum 75 --t-eff-us 8.6

The hardware half is acquire.tcl (one Vivado session); this file builds the
plan, launches it, then analyses the CSVs and writes the model.
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
from pathlib import Path

import numpy as np

from wscan import acquire, frames, geom, profile, vertical

VIVADO = r"D:\Xilinx\2025.1\Vivado\bin\vivado.bat"
HERE = Path(__file__).resolve().parent
ACQUIRE = HERE / "fpga" / "acquire.tcl"
MM_PER_STEP = profile.SCREW_LEAD_MM / profile.STEPS_PER_REV_DEFAULT
DEG_PER_STEP = 360.0 / profile.STEPS_PER_REV_DEFAULT


# --------------------------------------------------------------------- plan
def build_points(z0, z1, layers, azimuths, datum, frames, tx):
    heights = [z0 + (z1 - z0) * i / max(layers - 1, 1) for i in range(layers)]
    z_cur, a_cur = float(datum), 0.0
    rows = []
    seq = 0
    for li, z in enumerate(heights):
        order = list(range(len(azimuths)))
        if li % 2:
            order.reverse()
        for j in order:
            az = azimuths[j]
            lift = int(round((z - z_cur) / MM_PER_STEP))
            rot = int(round((az - a_cur) / DEG_PER_STEP))
            z_cur, a_cur = z, az
            rows.append({"seq": seq, "lat": 0.0, "az": az, "z": round(z, 3),
                         "lift": abs(lift), "lift_dir": 1 if lift >= 0 else 0,
                         "rot": abs(rot), "rot_dir": 1 if rot >= 0 else 0,
                         "frames": frames, "tx": tx})
            seq += 1
    return rows


def emit_plan(rows, path: Path) -> None:
    lines = ["# generated by auto_measure.py", "set plan_points {"]
    for p in rows:
        lines.append("  {seq %d lat %.3f az %.3f z %.3f lift %d lift_dir %d rot %d rot_dir %d frames %d}"
                     % (p["seq"], p["lat"], p["az"], p["z"], p["lift"], p["lift_dir"],
                        p["rot"], p["rot_dir"], p["frames"]))
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_vivado(script: Path, extra: list[str], log: Path) -> int:
    cmd = [VIVADO, "-mode", "batch", "-nojournal", "-nolog", "-notrace",
           "-source", str(script), "-tclargs", *extra]
    print("  $", " ".join(cmd[:1] + ["..."]) + f"  ({len(extra)} args)")
    with log.open("w", encoding="utf-8") as handle:
        proc = subprocess.run(cmd, capture_output=True, text=True)
        handle.write(proc.stdout)
        handle.write(proc.stderr)
    return proc.returncode


# ------------------------------------------------------------------- check
def cmd_check(args) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    log = out / "check.log"
    rc = run_vivado(HERE / "fpga" / "merged_check.tcl", [], log)
    text = log.read_text(encoding="utf-8", errors="ignore")
    ok = "CHECK_DONE" in text and "VIO" in text
    printf = [l for l in text.splitlines() if l.startswith(("VIO ", "  IN", "  OUT"))]
    for line in printf[:20]:
        print("  " + line)
    print(f"check: {'PASS' if ok else 'FAIL'}  log={log}")
    return 0 if ok else 2


# --------------------------------------------------------------- calibrate
def capture_one(out: Path, datum: float, frames_n: int, tx: int) -> Path:
    plan = build_points(datum, datum, 1, [0.0], datum, frames_n, tx)
    plan_tcl = out / "calib_plan.tcl"
    emit_plan(plan, plan_tcl)
    rc = run_vivado(ACQUIRE, ["--plan", str(plan_tcl), "--out", str(out),
                              "--frames", str(frames_n), "--tx", str(tx),
                              "--limit", "1"], out / "calib.log")
    if rc != 0:
        raise RuntimeError(f"acquisition failed, see {out/'calib.log'}")
    return out


def cmd_calibrate(args) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    distances = [float(d) for d in args.distances.split(",")]
    peaks = []
    print("Calibration: put the flat plate at each distance, then press Enter.")
    for d in distances:
        input(f"  plate at {d:.0f} mm (measured) — Enter to capture ...")
        capture_one(out / f"calib_{int(d)}", args.datum, 3, 1)
        run_dir = out / f"calib_{int(d)}"
        manifest = (run_dir / "manifest.jsonl").read_text(encoding="utf-8").splitlines()
        ts = []
        for line in manifest:
            m = json.loads(line)
            f = frames.to_frame(frames.read_ila_csv(run_dir / m["file"]),
                                frame_id=m["file"])
            pk = frames.detect(frames.prepare(f), profile.WINDOW_US)
            if pk is not None and pk.snr_db >= args.min_snr:
                ts.append(pk.t_us)
        if len(ts) < 2:
            print(f"  {d} mm: no stable peak ({len(ts)}/3) — calibration aborted")
            return 2
        peaks.append((d, float(np.median(ts))))
        print(f"  {d} mm: t={np.median(ts):.2f} us  ({len(ts)}/3 frames)")

    train = peaks[:-2] if len(peaks) >= 4 else peaks
    hold = peaks[-2:] if len(peaks) >= 4 else []
    cal = geom.fit_calibration([p[1] for p in train], [p[0] for p in train],
                               ident="plate_" + "_".join(str(int(p[0])) for p in train))
    errs = []
    for d, t in hold:
        path = cal.peak_to_path_mm(t)
        half = path / 2.0
        inner = half * half - (profile.PROBE_SPACING_MM / 2.0) ** 2
        est = math.sqrt(inner) if inner > 0 else float("nan")
        errs.append(est - d)
    cal = geom.Calibration(cal.t_eff_us, cal.sound_speed_m_s, cal.ident,
                           cal.residual_us,
                           float(max(abs(e) for e in errs)) if errs else float("nan"))
    doc = {"t_eff_us": cal.t_eff_us, "sound_speed_m_s": cal.sound_speed_m_s,
           "ident": cal.ident, "residual_us": cal.residual_us,
           "holdout_error_mm": cal.holdout_error_mm, "provisional": True,
           "distances_mm": [p[0] for p in peaks], "peaks_us": [p[1] for p in peaks]}
    (out / "calibration.json").write_text(json.dumps(doc, ensure_ascii=False, indent=2),
                                          encoding="utf-8")
    print(f"calibration: t_eff={cal.t_eff_us:.3f} us  residual={cal.residual_us:.3f} us "
          f"holdout={cal.holdout_error_mm:.2f} mm -> {out/'calibration.json'}")
    return 0 if (not errs or max(abs(e) for e in errs) <= args.max_error) else 2


# ---------------------------------------------------------------- preflight
def load_calibration(out: Path, args):
    cal_path = Path(args.calibration) if getattr(args, "calibration", None) else out / "calibration.json"
    if cal_path.exists():
        d = json.loads(cal_path.read_text(encoding="utf-8"))
        return geom.Calibration(d["t_eff_us"], d.get("sound_speed_m_s", 1480.0),
                                d.get("ident", "plate"), d.get("residual_us", float("nan")),
                                d.get("holdout_error_mm", float("nan")), True), cal_path
    if getattr(args, "t_eff_us", None) is not None:
        return geom.Calibration(args.t_eff_us, 1480.0, "provisional", provisional=True), None
    return None, None


def cmd_preflight(args) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    calib, src = load_calibration(out, args)
    if calib is None:
        print("preflight: no calibration; refusing to evaluate radii")
        return 2
    azimuths = [float(a) for a in args.azimuths.split(",")]
    points = build_points(args.datum, args.datum, 1, azimuths, args.datum,
                          args.frames, 1)
    emit_plan(points, out / "preflight_plan.tcl")
    print(f"preflight: {len(points)} points at z={args.datum}, {args.frames} frames each")
    if args.dry_run:
        return 0
    rc = run_vivado(ACQUIRE, ["--plan", str(out / "preflight_plan.tcl"), "--out", str(out),
                              "--frames", str(args.frames), "--tx", "1"],
                    out / "preflight.log")
    if rc != 0:
        print("preflight: acquisition failed")
        return 2
    report = acquire.analyse(out, out / "result", calib)
    rows = [json.loads(l) for l in (out / "result" / "observations.jsonl")
            .read_text(encoding="utf-8").splitlines()]
    radii = [r["radius_mm"] for r in rows if r.get("radius_mm") is not None]
    snrs = [r["snr_db"] for r in rows if r.get("snr_db") is not None]
    spread = (max(radii) - min(radii)) if len(radii) >= 2 else float("nan")
    print(f"  points with radius: {len(radii)}/{len(rows)}  "
          f"spread: {spread if spread == spread else float('nan'):.2f} mm  "
          f"snr max: {max(snrs) if snrs else float('nan'):.1f} dB")
    ok = len(radii) >= 2 and spread <= args.spread
    print(f"preflight: {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 2


def cmd_measure(args) -> int:
    """Full sequence: preflight -> scan -> model, stopping on a failed gate."""
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if not args.skip_preflight:
        print("== stage 1/2: preflight ==")
        rc = cmd_preflight(args)
        if rc != 0:
            print("stopped at preflight: fix the acoustic link before scanning")
            return rc
    print("== stage 2/2: scan ==")
    return cmd_run(args)


# --------------------------------------------------------------------- run
def cmd_run(args) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    calib = None
    cal_path = Path(args.calibration) if args.calibration else out / "calibration.json"
    if cal_path.exists():
        d = json.loads(cal_path.read_text(encoding="utf-8"))
        calib = geom.Calibration(d["t_eff_us"], d.get("sound_speed_m_s", 1480.0),
                                 d.get("ident", "plate"), d.get("residual_us", float("nan")),
                                 d.get("holdout_error_mm", float("nan")), True)
        print(f"calibration: {cal_path}  t_eff={calib.t_eff_us:.3f} us")
    elif args.t_eff_us is not None:
        calib = geom.Calibration(args.t_eff_us, 1480.0, "provisional", provisional=True)
        print(f"calibration: provisional t_eff={args.t_eff_us} us (no plate measurement)")
    else:
        print("no calibration: distances and radii will NOT be produced")

    azimuths = [float(a) for a in args.azimuths.split(",")]
    points = build_points(args.z0, args.z1, args.layers, azimuths,
                          args.datum, args.frames, args.tx)
    emit_plan(points, out / "plan.tcl")
    print(f"plan: {len(points)} points  z={args.z0}..{args.z1} ({args.layers} layers)  "
          f"az={azimuths}  frames={args.frames}  tx={args.tx}")

    if args.dry_run:
        print("dry run: plan written, nothing executed")
        return 0

    rc = run_vivado(ACQUIRE, ["--plan", str(out / "plan.tcl"), "--out", str(out),
                              "--frames", str(args.frames), "--tx", str(args.tx)],
                    out / "acquire.log")
    if rc != 0:
        print(f"acquisition failed: see {out/'acquire.log'}")
        return 2

    report = acquire.analyse(out, out / "result", calib)
    report["plan_args"] = {"z0": args.z0, "z1": args.z1, "layers": args.layers,
                           "azimuths": azimuths, "frames": args.frames, "tx": args.tx}
    (out / "result" / "scan_report.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    _write_summary(out, report)
    print(f"points={report['counts']['points']} frames={report['counts']['frames']} "
          f"with_radius={report['counts']['with_radius']}  reasons={report['reasons']}")
    for row in report["profile"]:
        print(f"  z={row['height_mm']:7.2f}  r={row['radius_median_mm']}  "
              f"spread={row['radius_spread_mm']}  n={row['points']}")
    if report["mesh"]:
        print(f"  mesh: {report['mesh']['triangles']} triangles")
    print(f"result -> {out/'result'}")
    return 0 if report["counts"]["with_radius"] else 3


def _write_summary(out: Path, report: dict) -> None:
    lines = ["# 自动测量结果", "",
             f"- 点/帧：{report['counts']['points']} / {report['counts']['frames']}",
             f"- 有半径的点：{report['counts']['with_radius']}",
             f"- 拒收原因：`{report['reasons']}`", ""]
    if report["mesh"]:
        lines += ["## 模型", "", f"```\n{report['mesh']}\n```", ""]
    lines += ["## 剖面", "", "| z mm | 半径 mm | 层内跨度 mm | 点数 |",
              "|---:|---:|---:|---:|"]
    for r in report["profile"]:
        lines.append(f"| {r['height_mm']} | {r['radius_median_mm']} | "
                     f"{r['radius_spread_mm']} | {r['points']} |")
    lines += ["", "## 边界", ""] + [f"- {x}" for x in report["limits"]]
    (out / "result" / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("check")
    c.add_argument("--out", default="out/check")
    c.set_defaults(func=cmd_check)

    k = sub.add_parser("calibrate")
    k.add_argument("--out", default="out/calib")
    k.add_argument("--distances", default="45,55,65,50,60")
    k.add_argument("--datum", type=float, default=75.0)
    k.add_argument("--min-snr", type=float, default=12.0)
    k.add_argument("--max-error", type=float, default=10.0)
    k.set_defaults(func=cmd_calibrate)

    r = sub.add_parser("run")
    r.add_argument("--out", required=True)
    r.add_argument("--z0", type=float, default=73.0)
    r.add_argument("--z1", type=float, default=77.0)
    r.add_argument("--layers", type=int, default=3)
    r.add_argument("--azimuths", default="0,90,180,270")
    r.add_argument("--frames", type=int, default=3)
    r.add_argument("--tx", type=int, default=1)
    r.add_argument("--datum", type=float, default=75.0)
    r.add_argument("--calibration", default=None)
    r.add_argument("--t-eff-us", type=float, default=None)
    r.add_argument("--dry-run", action="store_true")
    r.set_defaults(func=cmd_run)
    r.add_argument("--skip-preflight", action="store_true")

    pf = sub.add_parser("preflight")
    pf.add_argument("--out", required=True)
    pf.add_argument("--datum", type=float, default=75.0)
    pf.add_argument("--azimuths", default="0,30,60")
    pf.add_argument("--frames", type=int, default=3)
    pf.add_argument("--spread", type=float, default=1.0)
    pf.add_argument("--calibration", default=None)
    pf.add_argument("--t-eff-us", type=float, default=None)
    pf.add_argument("--dry-run", action="store_true")
    pf.set_defaults(func=cmd_preflight)

    mm = sub.add_parser("measure")
    mm.add_argument("--out", required=True)
    mm.add_argument("--z0", type=float, default=73.0)
    mm.add_argument("--z1", type=float, default=77.0)
    mm.add_argument("--layers", type=int, default=3)
    mm.add_argument("--azimuths", default="0,90,180,270")
    mm.add_argument("--frames", type=int, default=3)
    mm.add_argument("--tx", type=int, default=1)
    mm.add_argument("--datum", type=float, default=75.0)
    mm.add_argument("--calibration", default=None)
    mm.add_argument("--t-eff-us", type=float, default=None)
    mm.add_argument("--spread", type=float, default=1.0)
    mm.add_argument("--skip-preflight", action="store_true")
    mm.add_argument("--dry-run", action="store_true")
    mm.set_defaults(func=cmd_measure)

    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())

