"""CLI for the full scan workflow.

    python run_workflow.py plan    --out out/plan.json
    python run_workflow.py simulate --out out/sim [--quick]
    python run_workflow.py ingest  --session <AAA session> --group direct_30mm_on --out out/ingest
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

from wscan import frames, geom, pipeline, profile, report, sources, vertical

TRAIN_MM = (45.0, 55.0, 65.0)
HOLDOUT_MM = (50.0, 60.0)


def calibrate_synthetic(src: sources.SyntheticScan) -> tuple[geom.Calibration, list[dict]]:
    rows = []
    for d in TRAIN_MM + HOLDOUT_MM:
        peaks = []
        for k in range(3):
            frame = src.plate_capture(d, k)
            prep = frames.prepare(frame)
            peak = frames.detect(prep, profile.WINDOW_US)
            if peak is not None:
                peaks.append(peak.t_us)
        rows.append({"distance_mm": d, "t_peak_us": float(np.median(peaks)),
                     "path_mm": geom.plate_path_mm(d)})
    train = [r for r in rows if r["distance_mm"] in TRAIN_MM]
    cal = geom.fit_calibration([r["t_peak_us"] for r in train],
                               [r["distance_mm"] for r in train],
                               ident="plate_45_55_65")
    for r in rows:
        path = cal.peak_to_path_mm(r["t_peak_us"])
        half = path / 2.0
        inner = half * half - (profile.PROBE_SPACING_MM / 2.0) ** 2
        r["distance_est_mm"] = math.sqrt(max(inner, 0.0))
        r["error_mm"] = r["distance_est_mm"] - r["distance_mm"]
    holdout = [abs(r["error_mm"]) for r in rows if r["distance_mm"] in HOLDOUT_MM]
    cal = geom.Calibration(cal.t_eff_us, cal.sound_speed_m_s, cal.ident,
                           cal.residual_us, float(max(holdout)), provisional=True)
    return cal, rows


def emit_tcl_plan(doc, path: Path) -> None:
    """Write the plan as a Tcl list so acquire.tcl needs no JSON parser."""
    lines = ["# generated by run_workflow.py plan --format tcl",
             "set plan_points {"]
    for p in doc["points"]:
        lines.append("  {seq %d lat %s az %s z %s lift %d lift_dir %d rot %d rot_dir %d frames %d}"
                     % (p["seq"], p["latitude_deg"], p["azimuth_deg"], p["probe_z_mm"],
                        p["lift_steps"], p["lift_dir"], p["rot_steps"], p["rot_dir"],
                        p["frames"]))
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_plan(args) -> int:
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if args.trial:
        # Three azimuths at the current datum height: no lift move, rotation only.
        rows = []
        az_cur = 0.0
        deg_per_step = 360.0 / profile.STEPS_PER_REV_DEFAULT
        for seq, az in enumerate((0.0, 30.0, 60.0)):
            rot = int(round((az - az_cur) / deg_per_step))
            az_cur = az
            rows.append({"seq": seq, "layer": 0, "azimuth_index": seq,
                         "latitude_deg": 0.0, "azimuth_deg": az,
                         "probe_z_mm": 75.0,
                         "lift_steps": 0, "lift_dir": 1,
                         "rot_steps": abs(rot), "rot_dir": 1 if rot >= 0 else 0,
                         "frames": 1, "tx_required": False})
        doc = {"schema": "scan-plan/1", "mode": "trial", "points": rows,
               "notes": ["trial plan: 3 points, rotation only, no lift move",
                         "used to validate acquire.tcl before a full scan"]}
        if args.format == "tcl":
            emit_tcl_plan(doc, out)
        else:
            out.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"trial plan -> {out}  points={len(rows)}")
        return 0

    plan = profile.ScanPlan()
    if args.quick:
        plan = profile.ScanPlan(latitudes=(-10.0, 0.0, 10.0),
                                azimuths=(0.0, 90.0, 180.0, 270.0))
    layers = profile.all_layers()
    z_cur = 75.0                      # declared datum; the operator confirms it
    az_cur = 0.0
    deg_per_step = 360.0 / profile.STEPS_PER_REV_DEFAULT
    mm_per_step = profile.SCREW_LEAD_MM / profile.STEPS_PER_REV_DEFAULT
    rows = []
    for li, lat, ai, az in plan.points():
        layer = layers[li]
        lift_steps = int(round((layer.probe_z_mm - z_cur) / mm_per_step))
        rot_steps = int(round((az - az_cur) / deg_per_step))
        z_cur = layer.probe_z_mm
        az_cur = az
        rows.append({
            "seq": len(rows), "layer": li, "azimuth_index": ai,
            "latitude_deg": lat, "azimuth_deg": az, "probe_z_mm": layer.probe_z_mm,
            "lift_steps": abs(lift_steps), "lift_dir": 1 if lift_steps >= 0 else 0,
            "rot_steps": abs(rot_steps), "rot_dir": 1 if rot_steps >= 0 else 0,
            "frames": plan.frames_per_point,
            "tx_required": True,
        })
    doc = {"schema": "scan-plan/1", "generated_by": "run_workflow.py",
           "profile": {"adc_rate_hz": profile.ADC_RATE_HZ,
                       "ila_rows": profile.ILA_ROWS,
                       "samples_per_frame": profile.ADC_SAMPLES,
                       "window_us": list(profile.WINDOW_US),
                       "steps_per_rev": profile.STEPS_PER_REV_DEFAULT},
           "budget": plan.estimate_s(), "points": rows,
           "notes": ["motor steps are open-loop commands from a declared datum",
                     "each point needs one TX and frames_per_point captures",
                     "the acquisition side must export one CSV per frame"]}
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if args.format == "tcl":
        emit_tcl_plan(doc, out)
    else:
        out.write_text(json.dumps(doc, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"plan -> {out}  points={len(rows)}  budget={plan.estimate_s()['total_s']:.0f}s")
    return 0


def cmd_simulate(args) -> int:
    out = Path(args.out)
    bump = ({"lat": 10.0, "az": 180.0, "height_mm": 3.0, "sigma_deg": 12.0}
            if args.defect else {"height_mm": 0.0})
    src = sources.SyntheticScan(seed=args.seed, bump=bump)
    cal, cal_rows = calibrate_synthetic(src)
    print(f"calibration t_eff={cal.t_eff_us:.3f} us  residual={cal.residual_us:.3f} us "
          f"holdout={cal.holdout_error_mm:.3f} mm")
    plan = profile.ScanPlan()
    if args.quick:
        plan = profile.ScanPlan(latitudes=(-10.0, 0.0, 10.0),
                                azimuths=(0.0, 90.0, 180.0, 270.0))
    result = pipeline.run_scan(src, cal, plan, out)
    obs = _load_observations(out)
    report.render(result, obs, out)
    (out / "manifest.json").write_text(
        json.dumps({"calibration_rows": cal_rows, "files": pipeline.file_manifest(out)},
                   ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"status={result['counts']}  mesh={(result['mesh'] or {}).get('stats', {}).get('triangles')}")
    print(f"arc={result['self_check']}")
    if result.get("truth_check"):
        print(f"truth={result['truth_check']}")
    print(f"output -> {out}")
    return 0


def cmd_ingest(args) -> int:
    out = Path(args.out)
    src = sources.AAAArchive(args.session, args.group)
    records = []
    for frame, pose in src.frames():
        prep = frames.prepare(frame)
        peak = frames.detect(prep, profile.WINDOW_US)
        records.append({
            "frame_id": frame.frame_id,
            "tx_on": frame.tx_on,
            "samples": int(len(frame)),
            "t_peak_us": None if peak is None else round(float(peak.t_us), 4),
            "snr_db": None if peak is None else round(float(peak.snr_db), 2),
            "second_ratio": None if peak is None else round(float(peak.second_ratio), 3),
            "at_edge": None if peak is None else bool(peak.at_edge),
            "reason": "no_candidate" if peak is None else "candidate_unverified",
            "note": "no pose and no calibration: this is not a distance or a 3D point",
        })
    out.mkdir(parents=True, exist_ok=True)
    (out / "ingest.json").write_text(json.dumps({
        "schema": "ingest/1", "session": str(src.session), "group": args.group,
        "frames": records,
        "limits": ["archived direct-path experiment: no scan pose",
                   "no acoustic evidence of a target echo",
                   "peaks are exploratory, not TOF estimates"],
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    found = sum(1 for r in records if r["t_peak_us"] is not None)
    print(f"ingested {len(records)} frames from {src.session.name}/{args.group}; "
          f"{found} have an in-window candidate")
    print(f"output -> {out / 'ingest.json'}")
    return 0


def _load_observations(out: Path):
    path = out / "observations.jsonl"
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        data = json.loads(line)
        rows.append(pipeline.Observation(**data))
    return rows


def cmd_axisym(args) -> int:
    out = Path(args.out)
    if args.object == "cylinder":
        obj = vertical.Cylinder(radius_mm=args.radius, z0_mm=args.z0, z1_mm=args.z1)
    else:
        obj = vertical.Cone(r_bottom_mm=args.r_bottom, r_top_mm=args.r_top,
                            z0_mm=args.z0, z1_mm=args.z1)
    cal, cal_rows = calibrate_synthetic(sources.SyntheticScan(seed=3))
    report_doc = vertical.run(obj, cal, out)
    print(f"object={report_doc['object']['kind']} points={report_doc['counts']['points']} "
          f"eligible={report_doc['counts']['eligible']}")
    for row in report_doc["profile"]:
        print(f"  z={row['height_mm']:7.2f}  r_vert={row['radius_vertical_mm']}  "
              f"z_ref={row['z_reflection_mm']}  r_shaped={row['radius_shaped_mm']}  "
              f"true={row['radius_true_mm']}  err_vert={row['error_vertical_mm']}")
    print(f"mesh={report_doc['mesh']}")
    print(f"output -> {out}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_plan = sub.add_parser("plan")
    p_plan.add_argument("--out", default="out/plan.json")
    p_plan.add_argument("--quick", action="store_true")
    p_plan.add_argument("--format", choices=["json", "tcl"], default="json")
    p_plan.add_argument("--trial", action="store_true")
    p_plan.set_defaults(func=cmd_plan)

    p_sim = sub.add_parser("simulate")
    p_sim.add_argument("--out", default="out/sim")
    p_sim.add_argument("--quick", action="store_true")
    p_sim.add_argument("--seed", type=int, default=7)
    p_sim.add_argument("--defect", action="store_true")
    p_sim.set_defaults(func=cmd_simulate)

    p_ing = sub.add_parser("ingest")
    p_ing.add_argument("--session", required=True)
    p_ing.add_argument("--group", required=True)
    p_ing.add_argument("--out", default="out/ingest")
    p_ing.set_defaults(func=cmd_ingest)

    p_ax = sub.add_parser("axisym")
    p_ax.add_argument("--object", choices=["cylinder", "cone"], default="cylinder")
    p_ax.add_argument("--radius", type=float, default=14.0)
    p_ax.add_argument("--r-bottom", type=float, default=16.0)
    p_ax.add_argument("--r-top", type=float, default=8.0)
    p_ax.add_argument("--z0", type=float, default=59.0)
    p_ax.add_argument("--z1", type=float, default=91.0)
    p_ax.add_argument("--out", default="out/axisym")
    p_ax.set_defaults(func=cmd_axisym)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())








