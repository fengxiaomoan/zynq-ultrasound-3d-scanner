"""Embed tools/live_model_page.html into the firmware as a C byte array.

The page has to ship inside the ELF (the PS bare-metal app has no file system),
and it must be the *same* file the PC viewer serves, so it is generated here
rather than copied by hand.

    python fpga/ps/sw/tools/gen_page.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

HERE = Path(__file__).resolve()
SW = HERE.parents[1]                       # src/ps/sw
ROOT = SW.parents[2]                       # package root
PAGE = ROOT / "src" / "host" / "tools" / "live_model_page.html"
OUT = SW / "src" / "page_html.h"


def main() -> int:
    ap = argparse.ArgumentParser()
    # --out / --page exist for CI-style checks and for the DSH sandbox, where a
    # subprocess may not be able to write into the repo tree; the firmware build
    # always uses the defaults.
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--page", default=str(PAGE))
    args = ap.parse_args()
    out_path = Path(args.out)
    page_path = Path(args.page)
    data = page_path.read_bytes()
    lines = [
        "/* generated by src/ps/sw/tools/gen_page.py -- do not edit */",
        "/* source: tools/live_model_page.html (%d bytes) */" % len(data),
        "#ifndef M2B_PAGE_HTML_H",
        "#define M2B_PAGE_HTML_H",
        "",
        "static const char PAGE_HTML[] = {",
    ]
    for i in range(0, len(data), 20):
        chunk = data[i:i + 20]
        lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
    lines += ["    0x00", "};", "", "#endif", ""]
    out_path.write_text("\n".join(lines), encoding="ascii")
    print(f"{len(data)} bytes -> {out_path} ({out_path.stat().st_size} bytes of C)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
